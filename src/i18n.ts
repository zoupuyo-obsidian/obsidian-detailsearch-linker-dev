type Messages = (typeof messages)['ja'];
export type I18nKey = keyof Messages;

const jaKeys = Object.keys(messages.ja) as I18nKey[];
const enKeys = Object.keys(messages.en) as I18nKey[];
if (jaKeys.length !== enKeys.length || jaKeys.some((k) => !enKeys.includes(k))) {
	throw new Error('i18n ja/en keys must match');
}

export function resolveUiLanguage(): UiLanguage {
	const lang = getLanguage();
	return lang === 'ja' ? 'ja' : 'en';
}

export function t(lang: UiLanguage, key: I18nKey): string {
	const value = messages[lang][key];
	if (typeof value === 'function') {
		throw new Error(`i18n key ${key} needs arguments`);
	}
	return value;
}

export function tf<K extends I18nKey>(
	lang: UiLanguage,
	key: K,
	...args: Messages[K] extends (...args: infer P) => string ? P : never
): string {
	const value = messages[lang][key];
	if (typeof value === 'function') {
		return (value as (...fnArgs: unknown[]) => string)(...args);
	}
	return value;
}
